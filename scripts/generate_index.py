#!/usr/bin/env python3
"""Generate a Markdown index of solution files from their header comments.

Run from the repository root:
    python scripts/generate_index.py

Files with missing or unreadable metadata are still listed, with unavailable
values marked as "Not provided".
"""

from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlparse

SOLUTION_NAME = re.compile(r"^practice(\d+)\.[A-Za-z0-9]+$", re.IGNORECASE)
HEADER_LINE = re.compile(
    r"^\s*(?:#|//)\s*(Problem|Source)\s*:\s*(.*?)\s*$",
    re.IGNORECASE,
)
MARKDOWN_LINK = re.compile(r"\[[^\]]*\]\((https?://[^\s)]+)\)", re.IGNORECASE)
URL = re.compile(r"https?://[^\s<>]+", re.IGNORECASE)


@dataclass(frozen=True)
class Solution:
    language: str
    number: int
    path: Path
    problem: str
    source: str


def clean_value(value: str) -> str:
    """Extract a URL from Markdown links or return the cleaned header value."""
    value = value.strip()
    link = MARKDOWN_LINK.search(value)
    if link:
        return link.group(1).rstrip(".,;")
    match = URL.search(value)
    if match:
        return match.group(0).rstrip(".,;")
    return value


def read_metadata(path: Path) -> tuple[str, str]:
    """Read Problem and Source fields from the leading comment block."""
    metadata: dict[str, str] = {}
    try:
        with path.open("r", encoding="utf-8-sig") as solution:
            for line_number, line in enumerate(solution):
                if line_number >= 10 or len(metadata) == 2:
                    break
                if not line.strip():
                    if metadata:
                        break
                    continue

                match = HEADER_LINE.match(line.rstrip("\r\n"))
                if match:
                    field, value = match.groups()
                    metadata.setdefault(field.casefold(), clean_value(value))
                elif metadata:
                    break
    except (OSError, UnicodeError):
        return "", ""

    return metadata.get("problem", ""), metadata.get("source", "")


def discover_solutions(solutions_dir: Path) -> list[Solution]:
    """Find numbered solution files and collect their metadata."""
    entries: list[Solution] = []
    for path in solutions_dir.rglob("*"):
        if not path.is_file():
            continue

        match = SOLUTION_NAME.fullmatch(path.name)
        if not match:
            continue

        relative_path = path.relative_to(solutions_dir)
        language = relative_path.parts[0].casefold() if len(relative_path.parts) > 1 else "unknown"
        problem, source = read_metadata(path)
        entries.append(
            Solution(
                language=language,
                number=int(match.group(1)),
                path=path,
                problem=problem,
                source=source,
            )
        )

    return sorted(
        entries,
        key=lambda item: (item.language, item.number, item.path.as_posix().casefold()),
    )


def escape_cell(value: str) -> str:
    """Escape characters that would break a Markdown table cell."""
    return value.replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def render_index(root: Path) -> tuple[str, int]:
    """Build the complete INDEX.md content and return its entry count."""
    solutions_dir = root / "solutions"
    if not solutions_dir.is_dir():
        raise FileNotFoundError(f"Solutions directory not found: {solutions_dir}")

    entries = discover_solutions(solutions_dir)
    lines = [
        "# Solutions Index",
        "",
        "<!-- Generated by python scripts/generate_index.py. Do not edit manually. -->",
        "",
        "| Problem | Source | Language | File |",
        "| --- | --- | --- | --- |",
    ]

    for entry in entries:
        problem = escape_cell(entry.problem) or "Not provided"
        source = escape_cell(entry.source)
        parsed = urlparse(source)
        if source and parsed.scheme in {"http", "https"} and parsed.netloc:
            source_cell = f"[Source]({source})"
        else:
            source_cell = source or "Not provided"

        relative_path = entry.path.relative_to(root).as_posix()
        file_cell = f"[{escape_cell(relative_path)}]({relative_path})"
        lines.append(
            f"| {problem} | {source_cell} | {escape_cell(entry.language)} | {file_cell} |"
        )

    lines.extend(["", f"Total solutions: **{len(entries)}**", ""])
    return "\n".join(lines), len(entries)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate INDEX.md from solution header comments."
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Repository root (defaults to the parent of scripts/).",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Output Markdown file (defaults to INDEX.md in the repository root).",
    )
    args = parser.parse_args()

    root = args.root.resolve()
    output = args.output.resolve() if args.output else root / "INDEX.md"

    try:
        content, count = render_index(root)
    except (FileNotFoundError, OSError) as error:
        parser.error(str(error))

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"Generated {output} with {count} solution entries.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
